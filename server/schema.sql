CREATE TABLE IF NOT EXISTS players (
 id UUID PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
 password_hash TEXT NOT NULL, preferences JSONB NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, player_id UUID NOT NULL REFERENCES players(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS games (id TEXT PRIMARY KEY, title TEXT NOT NULL, authority TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS matches (
 id UUID PRIMARY KEY, game_id TEXT NOT NULL REFERENCES games(id), started_at TIMESTAMPTZ NOT NULL DEFAULT now(), ended_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS runs (
 id UUID NOT NULL, player_id UUID NOT NULL REFERENCES players(id) ON DELETE CASCADE,
 game_id TEXT NOT NULL REFERENCES games(id), match_id UUID REFERENCES matches(id), mode TEXT NOT NULL CHECK(mode IN ('offline','online')),
 score DOUBLE PRECISION NOT NULL CHECK(score>=0), duration_ms INTEGER NOT NULL CHECK(duration_ms>=0), won BOOLEAN NOT NULL,
 stats JSONB NOT NULL, verified BOOLEAN NOT NULL DEFAULT false, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(player_id,id)
);
CREATE INDEX IF NOT EXISTS runs_player_game ON runs(player_id,game_id,created_at DESC);
CREATE TABLE IF NOT EXISTS progress (
 player_id UUID NOT NULL REFERENCES players(id) ON DELETE CASCADE, game_id TEXT NOT NULL REFERENCES games(id),
 best DOUBLE PRECISION NOT NULL DEFAULT 0, plays INTEGER NOT NULL DEFAULT 0, wins INTEGER NOT NULL DEFAULT 0,
 total_ms BIGINT NOT NULL DEFAULT 0, stats JSONB NOT NULL DEFAULT '{}', updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(player_id,game_id)
);
CREATE TABLE IF NOT EXISTS checkpoints (
 player_id UUID NOT NULL REFERENCES players(id) ON DELETE CASCADE,
 game_id TEXT NOT NULL REFERENCES games(id), data JSONB NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(player_id,game_id)
);
ALTER TABLE matches ADD COLUMN IF NOT EXISTS state JSONB NOT NULL DEFAULT '{}';

CREATE TABLE IF NOT EXISTS rts_rooms (id UUID PRIMARY KEY, code TEXT UNIQUE NOT NULL, state BYTEA NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS rts_frames (room_id UUID NOT NULL REFERENCES rts_rooms(id) ON DELETE CASCADE, tick INTEGER NOT NULL, commands BYTEA NOT NULL, PRIMARY KEY(room_id,tick));
CREATE TABLE IF NOT EXISTS rts_checkpoints (player_id UUID PRIMARY KEY REFERENCES players(id) ON DELETE CASCADE, state BYTEA NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS fps_matches (id UUID PRIMARY KEY, state JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), ended_at TIMESTAMPTZ);
